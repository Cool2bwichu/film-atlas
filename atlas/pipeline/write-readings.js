const seen = new Set();
const edges = [];
for (const e of EDGES) {
  if (!films[e.a] || !films[e.b]) { missing.push(e.a + " -> " + e.b); continue; }
  const sig = [e.a, e.b].sort().join("|") + "|" + e.type;
  if (seen.has(sig)) continue;
  seen.add(sig);
  edges.push(e);
}

